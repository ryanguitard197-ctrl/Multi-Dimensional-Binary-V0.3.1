fn domain_matches(query: &str, name: &str, desc: &str) -> bool {
    let synonyms: Vec<(&str, Vec<&str>)> = vec![
        ("bio", vec!["protein", "drug", "genom", "pharma", "medical"]),
        ("chem", vec!["material", "compound", "molecule", "drug"]),
        ("tech", vec!["network", "crypto", "quantum", "routing"]),
        ("money", vec!["financ", "portfolio", "invest", "stock"]),
        ("earth", vec!["climate", "water", "energy", "agri", "environment"]),
    ];

    for (key, syns) in &synonyms {
        if query.contains(key) {
            for syn in syns {
                if name.contains(syn) || desc.contains(syn) {
                    return true;
                }
            }
        }
    }
    false
}

/// Parse CSV content into a JSON value.
fn parse_csv_to_json(content: &str, expected_type: &FieldType) -> Result<serde_json::Value, String> {
    let lines: Vec<&str> = content.lines().collect();
    if lines.is_empty() {
        return Err("Empty CSV file".to_string());
    }

    match expected_type {
        FieldType::FloatArray => {
            // Single column or single row
            let values: Result<Vec<f64>, _> = lines
                .iter()
                .filter(|l| !l.is_empty())
                .flat_map(|l| l.split(','))
                .map(|v| v.trim().parse::<f64>())
                .collect();
            let values = values.map_err(|e| format!("CSV parse error: {}", e))?;
            Ok(serde_json::json!(values))
        }
        FieldType::FloatMatrix => {
            let matrix: Result<Vec<Vec<f64>>, _> = lines
                .iter()
                .filter(|l| !l.is_empty())
                .map(|line| {
                    line.split(',')
                        .map(|v| v.trim().parse::<f64>())
                        .collect::<Result<Vec<f64>, _>>()
                })
                .collect();
            let matrix = matrix.map_err(|e| format!("CSV matrix parse error: {}", e))?;
            Ok(serde_json::json!(matrix))
        }
        _ => {
            // Return as string
            Ok(serde_json::Value::String(content.to_string()))
        }
    }
}

