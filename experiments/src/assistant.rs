    /// Load data from a file or URL.
    fn load_from_source(
        &self,
        path: &str,
        expected_type: &FieldType,
    ) -> Result<(serde_json::Value, DataSource), String> {
        if path.starts_with("http://") || path.starts_with("https://") {
            // URL source — mark provenance, actual fetch happens externally
            Ok((
                serde_json::Value::Null,
                DataSource::url(path),
            ))
        } else {
            // File source
            let content = std::fs::read_to_string(path)
                .map_err(|e| format!("Cannot read '{}': {}", path, e))?;

            let value = if path.ends_with(".json") {
                serde_json::from_str(&content)
                    .map_err(|e| format!("Invalid JSON in '{}': {}", path, e))?
            } else if path.ends_with(".csv") {
                parse_csv_to_json(&content, expected_type)?
            } else {
                // Try JSON first, then treat as string
                serde_json::from_str(&content)
                    .unwrap_or(serde_json::Value::String(content))
            };

            Ok((value, DataSource::file(path)))
        }
    }
