    // ── Explain results ─────────────────────────────────────────────

    /// Explain experiment results in plain English.
    pub fn explain_results(
        &self,
        definition: &ExperimentDefinition,
        result: &DiscoveryResult,
    ) -> ResultExplanation {
        let strategy = &result.strategy_used;
        let score = result.best_score;
        let candidates = result.candidates_evaluated;
        let intact = result.superposition_intact;

        let summary = format!(
            "MDB discovered a solution scoring {:.4} after evaluating {} candidates using {}.",
            score, candidates, strategy
        );

        let solution_meaning = format!(
            "Best solution: {}\n\
             This represents the optimal configuration found by the MDB engine. \
             The pattern was discovered (not predetermined) by exploring the state \
             space without collapsing superposition.",
            result.best_solution.interpretation
        );

        let confidence = if intact && candidates > 100 {
            "High — superposition remained intact and a large candidate space was evaluated.".to_string()
        } else if intact {
            "Moderate — superposition intact but small candidate space. Consider increasing candidates.".to_string()
        } else {
            "Lower — superposition was disrupted. Results may not represent the global optimum.".to_string()
        };

        let mut next_steps = vec![
            "Review the reproducibility manifest for full provenance".to_string(),
            "Verify the solution against domain-specific criteria".to_string(),
        ];

        if result.ranked_solutions.len() > 1 {
            next_steps.push(format!(
                "Examine the {} alternative solutions for diversity",
                result.ranked_solutions.len() - 1
            ));
        }

        if !intact {
            next_steps.push("Re-run with different parameters to verify robustness".to_string());
        }

        match &definition.success_criteria {
            SuccessCriteria::BeatBaseline { baseline, description } => {
                next_steps.push(format!("Compare against baseline ({}: {:.4})", description, baseline));
            }
            SuccessCriteria::NovelDiscovery { .. } => {
                next_steps.push("Assess novelty against existing literature/databases".to_string());
            }
            _ => {}
        }

        let detailed = format!(
            "Experiment: {}\n\
             Strategy: {}\n\
             Candidates evaluated: {}\n\
             Superposition intact: {}\n\
             Best score: {:.6}\n\
             Ranked alternatives: {}\n\
             Execution time: {}ms",
            definition.name,
            strategy,
            candidates,
            intact,
            score,
            result.ranked_solutions.len(),
            result.execution_time_ms,
        );

        ResultExplanation {
            summary,
            detailed,
            solution_meaning,
            confidence_assessment: confidence,
            next_steps,
            baseline_comparison: None,
        }
    }

