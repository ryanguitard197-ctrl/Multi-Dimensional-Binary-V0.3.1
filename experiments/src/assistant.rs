/// An experiment plan generated by the assistant.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ExperimentPlan {
    /// Suggested experiment name.
    pub name: String,
    /// What we understand the problem to be.
    pub problem_summary: String,
    /// Recommended problem type.
    pub problem_type: ProblemType,
    /// Recommended encoding.
    pub encoding: StateSpaceEncoding,
    /// Recommended solver strategy.
    pub strategy: SolverStrategy,
    /// All required data inputs.
    pub required_data: Vec<DataRequirement>,
    /// Optional data inputs.
    pub optional_data: Vec<DataRequirement>,
    /// Recommended success criteria.
    pub success_criteria: SuccessCriteria,
    /// Tags for this experiment.
    pub tags: Vec<String>,
    /// Why we chose this configuration.
    pub reasoning: String,
    /// Confidence in the plan (0.0 – 1.0).
    pub confidence: f64,
    /// Warnings or things to consider.
    pub warnings: Vec<String>,
}

/// A single data requirement identified by the assistant.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DataRequirement {
    /// Field name.
    pub field_name: String,
    /// Human-readable description.
    pub description: String,
    /// Data type.
    pub field_type: FieldType,
    /// Unit of measurement (if applicable).
    pub unit: Option<String>,
    /// Min/max bounds (if applicable).
    pub bounds: Option<(f64, f64)>,
    /// Where to find this data.
    pub suggested_source: String,
    /// Example value (for clarity).
    pub example: String,
    /// Why this data is needed.
    pub rationale: String,
    /// Whether provenance is required.
    pub requires_provenance: bool,
}

/// A request to send to an AI backend.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AssistantRequest {
    /// The system prompt for the AI.
    pub system_prompt: String,
    /// The user's message.
    pub user_message: String,
    /// Expected response format.
    pub response_format: ResponseFormat,
    /// Temperature for generation.
    pub temperature: f64,
}

/// Expected response format from the AI.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum ResponseFormat {
    /// Free-form text.
    Text,
    /// Structured JSON matching a schema.
    Json { schema: String },
    /// An ExperimentPlan.
    ExperimentPlan,
    /// A list of DataRequirements.
    DataRequirements,
    /// Plain English explanation.
    Explanation,
}

/// A suggestion for an experiment the user could run.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ExperimentSuggestion {
    /// Suggested experiment name.
    pub name: String,
    /// What it would investigate.
    pub description: String,
    /// Estimated complexity (1–10).
    pub complexity: u8,
    /// Estimated data requirements (1=minimal, 10=extensive).
    pub data_effort: u8,
    /// Potential impact description.
    pub potential_impact: String,
    /// Whether a template already exists in the catalog.
    pub has_template: bool,
    /// Template name if it exists.
    pub template_name: Option<String>,
}

/// Result explanation in plain English.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ResultExplanation {
    /// One-line summary.
    pub summary: String,
    /// Detailed explanation.
    pub detailed: String,
    /// What the best solution means in context.
    pub solution_meaning: String,
    /// How confident we are in the result.
    pub confidence_assessment: String,
    /// Suggested next steps.
    pub next_steps: Vec<String>,
    /// Comparison to known baselines (if available).
    pub baseline_comparison: Option<String>,
}

