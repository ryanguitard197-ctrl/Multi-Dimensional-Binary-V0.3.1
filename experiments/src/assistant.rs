//! # AI Experiment Assistant
//!
//! Go from "I have a problem" to "I have a running experiment" with
//! AI-powered planning. The assistant:
//!
//! 1. Takes a natural-language problem description
//! 2. Analyzes it to determine problem type, encoding, and strategy
//! 3. Generates the complete input schema (what data you need)
//! 4. Suggests where to find each piece of data
//! 5. Can auto-fill inputs from data sources (files, APIs, databases)
//! 6. Explains results in plain English after the run
//!
//! ## Design
//!
//! The assistant is designed to be pluggable — it emits structured
//! `AssistantRequest` objects that can be sent to any LLM backend
//! (OpenAI, Anthropic, local models, etc.). This keeps the framework
//! vendor-agnostic while enabling full AI integration.
//!
//! ## Usage
//!
//! ```rust
//! let assistant = ExperimentAssistant::new();
//!
//! // Plan an experiment from a description
//! let plan = assistant.plan_experiment("I want to optimize traffic flow...");
//!
//! // Refine the plan
//! let plan = assistant.refine_plan(plan, "Add a constraint for max budget");
//!
//! // Auto-fill inputs from data files
//! let inputs = assistant.auto_fill(&experiment, &[
//!     ("traffic_data", "/data/traffic.csv"),
//!     ("road_network", "/data/roads.geojson"),
//! ]);
//! ```

