    /// Generate a name for the experiment from the description.
    fn generate_experiment_name(&self, description: &str) -> String {
        let lower = description.to_lowercase();
        let words: Vec<&str> = lower.split_whitespace().collect();

        // Look for key noun phrases
        if lower.contains("cell tower") || lower.contains("tower placement") {
            return "Cell Tower Placement Optimization".to_string();
        }
        if lower.contains("traffic") && (lower.contains("signal") || lower.contains("flow")) {
            return "Traffic Signal Optimization".to_string();
        }
        if lower.contains("supply chain") {
            return "Supply Chain Network Optimization".to_string();
        }
        if lower.contains("protein") && lower.contains("fold") {
            return "Protein Folding Discovery".to_string();
        }
        if lower.contains("drug") && (lower.contains("discover") || lower.contains("design")) {
            return "Drug Candidate Discovery".to_string();
        }
        if lower.contains("portfolio") || (lower.contains("invest") && lower.contains("optim")) {
            return "Investment Portfolio Optimization".to_string();
        }
        if lower.contains("route") || lower.contains("routing") {
            return "Route Optimization".to_string();
        }
        if lower.contains("schedul") {
            return "Schedule Optimization".to_string();
        }

        // Fall back to first significant words
        let skip = &["i", "want", "to", "find", "the", "an", "a", "of", "for", "my", "our", "how", "can"];
        let significant: Vec<&&str> = words.iter()
            .filter(|w| !skip.contains(w) && w.len() > 2)
            .take(4)
            .collect();

        if significant.is_empty() {
            "Custom MDB Experiment".to_string()
        } else {
            let name: String = significant.iter()
                .map(|w| {
                    let mut c = w.chars();
                    match c.next() {
                        None => String::new(),
                        Some(f) => f.to_uppercase().to_string() + c.as_str(),
                    }
                })
                .collect::<Vec<_>>()
                .join(" ");
            format!("{} Optimization", name)
        }
    }

